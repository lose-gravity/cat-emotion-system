# -*- coding: utf-8 -*-
"""
00_gen_tables.py —— 从CSV生成C头文件 tables.h
============================================
产物: tables.h 内含
  MEL_SPARSE: mel_nz[128], mel_col[128][MAXNZ], mel_val[128][MAXNZ]  (稀疏三角滤波)
  DCT:        dct40[40][128]
  HANN400:    hann400[400]
  HANN2048:   hann2048[2048]
  SAVGOL:     sg1[151][151], sg2[151][151]  (delta线性算子, 稠密存法, HLS优化时再转FIR)
"""
import os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PARENT = os.path.dirname(HERE)


def load(name):
    return np.loadtxt(os.path.join(PARENT, name), delimiter=",")


def main():
    mel = load("mel_128x1025.csv")
    dct = load("dct_40x128.csv")
    h400 = load("hann_400.csv")
    h2048 = load("hann_2048.csv")
    sg1 = load("savgol_d1.csv")
    sg2 = load("savgol_d2.csv")
    sg1_51 = load("savgol_d1_51.csv")
    sg2_51 = load("savgol_d2_51.csv")

    def cfmt(v):
        s = f"{v:.12g}"
        if "e" not in s and "." not in s:
            s += ".0"
        return s

    # mel稀疏化: 每行非零项
    nz_counts = (mel != 0).sum(axis=1)
    maxnz = int(nz_counts.max())
    assert np.allclose(np.sort(nz_counts)[::-1][:5], np.sort(nz_counts)[::-1][:5])

    out = []
    out.append("/* tables.h - auto-generated by 00_gen_tables.py, do not edit */")
    out.append(f"#define MEL_NROWS 128")
    out.append(f"#define MEL_NCOLS 1025")
    out.append(f"#define MEL_MAXNZ {maxnz}")
    out.append(f"#define N_FFT 2048")
    out.append(f"#define N_HALF 1025")
    out.append("")
    out.append(f"static const int mel_nz[{128}] = {{")
    out.append("    " + ", ".join(str(int(v)) for v in nz_counts))
    out.append("};")
    out.append("")
    # col索引
    out.append(f"static const int mel_col[{128}][{maxnz}] = {{")
    for i in range(128):
        cols = np.nonzero(mel[i])[0]
        cols = list(cols) + [0] * (maxnz - len(cols))
        out.append("    {" + ", ".join(str(int(v)) for v in cols) + "},")
    out.append("};")
    out.append("")
    # 值
    out.append(f"static const double mel_val[{128}][{maxnz}] = {{")
    for i in range(128):
        vals = mel[i][mel[i] != 0]
        vals = list(vals) + [0.0] * (maxnz - len(vals))
        out.append("    {" + ", ".join(cfmt(v) for v in vals) + "},")
    out.append("};")
    out.append("")

    def mat(name, arr, dtype="double"):
        r, c = arr.shape
        out.append(f"static const {dtype} {name}[{r}][{c}] = {{")
        for row in arr:
            out.append("    {" + ", ".join(cfmt(v) for v in row) + "},")
        out.append("};")
        out.append("")

    mat("dct40", dct)
    mat("hann400", h400.reshape(1, -1))
    mat("hann2048", h2048.reshape(1, -1))
    mat("sg1", sg1)
    mat("sg2", sg2)
    mat("sg1_51", sg1_51)
    mat("sg2_51", sg2_51)

    with open(os.path.join(HERE, "tables.h"), "w", encoding="ascii") as f:
        f.write("\n".join(out))
    print(f"tables.h 生成完成: mel稀疏(maxnz={maxnz}), dct 40x128, hann, sg1/sg2 151x151")
    print(f"文件大小: {os.path.getsize(os.path.join(HERE, 'tables.h'))/1e6:.1f}MB")


if __name__ == "__main__":
    main()
